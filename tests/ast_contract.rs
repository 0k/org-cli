//! Cross-language contract test for the semantic Org AST.
//!
//! [`org_cli::org::ast`] is not consumed only by this crate. Its serialized
//! shape crosses a process boundary and a language boundary:
//!
//! ```text
//!   org-cli::org::ast  ──serde_json──>  vigil-watch /api/data-flow/item
//!                                             │
//!                                             ▼
//!                            vigil-ui  frontend/src/types/orgAst.ts
//!                            vigil-ui  components/org/OrgNode.vue
//! ```
//!
//! Nothing in the Rust type system reaches across that boundary, and the
//! TypeScript side decodes with a bare `as OrgDocumentNode` assertion — a
//! compile-time claim that performs no runtime check. So a renamed field or
//! a changed `type` discriminator would compile clean on BOTH sides and
//! surface only as a silently blank pane in the UI.
//!
//! This test pins the shape. `fixtures/ast-contract.org` is the input;
//! `fixtures/ast-contract.json` is the exact expected serialization, and is
//! *generated by the converter itself* rather than written by hand, so it
//! can never disagree with the code by transcription error:
//!
//! ```sh
//! UPDATE_AST_CONTRACT=1 cargo test --test ast_contract
//! ```
//!
//! Regenerating is deliberately a manual, reviewable act. When the diff on
//! that JSON file is not what you intended, the renderer in the other
//! repository is about to break.
//!
//! The same fixture is read by vigil-ui's `vitest` suite
//! (`frontend/src/__tests__/orgAstContract.test.ts`), which type-checks it
//! against `orgAst.ts` and walks every node. One file, two languages: that
//! is what makes the shapes unable to drift apart.

use std::path::{Path, PathBuf};

use org_cli::org::ast::parse_ast;
use serde_json::Value;

fn fixture_dir() -> PathBuf {
    Path::new(env!("CARGO_MANIFEST_DIR")).join("tests/fixtures")
}

/// Serialize the fixture document through the real converter.
fn actual() -> Value {
    let input = std::fs::read_to_string(fixture_dir().join("ast-contract.org"))
        .expect("ast-contract.org fixture must exist");
    serde_json::to_value(parse_ast(&input)).expect("AST must serialize")
}

fn walk<'a>(value: &'a Value, node_type: &str, out: &mut Vec<&'a Value>) {
    match value {
        Value::Object(map) => {
            if map.get("type").and_then(Value::as_str) == Some(node_type) {
                out.push(value);
            }
            for child in map.values() {
                walk(child, node_type, out);
            }
        }
        Value::Array(values) => {
            for child in values {
                walk(child, node_type, out);
            }
        }
        _ => {}
    }
}

fn nodes_of_type<'a>(value: &'a Value, node_type: &str) -> Vec<&'a Value> {
    let mut out = Vec::new();
    walk(value, node_type, &mut out);
    out
}

/// The serialized AST equals the checked-in fixture, byte for byte.
///
/// This is the drift tripwire. It intentionally compares the WHOLE
/// document rather than sampling fields, because the failure it guards
/// against is a field the assertions forgot to name.
#[test]
fn serialized_ast_matches_the_shared_cross_language_fixture() {
    let actual = actual();
    let expected_path = fixture_dir().join("ast-contract.json");
    let rendered = serde_json::to_string_pretty(&actual).expect("AST must render") + "\n";

    if std::env::var_os("UPDATE_AST_CONTRACT").is_some() {
        std::fs::write(&expected_path, &rendered).expect("fixture must be writable");
        return;
    }

    let expected_text = std::fs::read_to_string(&expected_path).unwrap_or_else(|_| {
        panic!(
            "missing {}; regenerate with UPDATE_AST_CONTRACT=1 cargo test --test ast_contract",
            expected_path.display()
        )
    });
    let expected: Value =
        serde_json::from_str(&expected_text).expect("fixture JSON must be well-formed");

    if actual != expected {
        let diff = similar::TextDiff::from_lines(&expected_text, &rendered);
        eprintln!();
        for line in diff
            .unified_diff()
            .header("expected (fixture)", "actual (converter)")
            .to_string()
            .lines()
        {
            if line.starts_with('-') {
                eprintln!("\x1b[31m{line}\x1b[0m");
            } else if line.starts_with('+') {
                eprintln!("\x1b[32m{line}\x1b[0m");
            } else if line.starts_with('@') {
                eprintln!("\x1b[36m{line}\x1b[0m");
            } else {
                eprintln!("{line}");
            }
        }
        panic!(
            "AST shape changed — this BREAKS vigil-ui's renderer.\n\
             If the change is intended, update vigil-ui's orgAst.ts and OrgNode.vue \
             in the same change, then regenerate with:\n  \
             UPDATE_AST_CONTRACT=1 cargo test --test ast_contract"
        );
    }
}

/// A canonical Emacs `CLOCK:` line parses as a *clock*, not a paragraph.
///
/// This is the single fact the patched `orgize` fork exists to deliver, and
/// the reason `Cargo.toml` carries a `[patch.crates-io]` entry. Upstream's
/// `repeater_or_delay` consumes the `+` of `+0100`, reads the digits, then
/// demands a unit suffix (`h`/`d`/`w`); finding none it fails the WHOLE
/// timestamp, and the line degrades to a plain paragraph.
///
/// That degradation is silent — no error, no panic, just a `CLOCK:` line
/// that has quietly become prose and vanished from every clock query. The
/// assertion below is what makes it loud. Both the offset-only form and the
/// seconds-bearing form are covered, because the fork fixes two distinct
/// parse failures.
#[test]
fn clock_lines_with_numerical_utc_offsets_and_seconds_parse_as_clocks() {
    let ast = actual();
    let clocks = nodes_of_type(&ast, "clock");

    assert_eq!(
        clocks.len(),
        3,
        "expected 3 clocks; a count of 0 means the orgize patch is not applied \
         and every CLOCK line degraded to a paragraph"
    );

    // Seconds precision, both ends, plus a seconds-bearing duration.
    let seconds = clocks
        .iter()
        .find(|clock| clock["start"]["second"] == "20")
        .expect("the seconds-bearing CLOCK must parse");
    assert_eq!(seconds["start"]["tz_offset"], "+0100");
    assert_eq!(seconds["start"]["hour"], "09");
    assert_eq!(seconds["end"]["second"], "25");
    assert_eq!(seconds["end"]["tz_offset"], "+0100");
    assert_eq!(seconds["duration"], "2:22:05");
    assert_eq!(seconds["running"], false);

    // Minute precision with a numerical offset.
    let minutes = clocks
        .iter()
        .find(|clock| clock["duration"] == "2:15")
        .expect("the minute-precision CLOCK must parse");
    assert_eq!(minutes["start"]["tz_offset"], "+0200");
    assert_eq!(minutes["start"]["second"], Value::Null);
    assert_eq!(minutes["end"]["minute"], "45");

    // An open clock: no end, no duration, still running.
    let running = clocks
        .iter()
        .find(|clock| clock["running"] == true)
        .expect("the open CLOCK must parse");
    assert_eq!(running["end"], Value::Null);
    assert_eq!(running["duration"], Value::Null);
    assert_eq!(running["start"]["tz_offset"], "+0200");
}

/// Every node kind the fixture is meant to exercise is actually present.
///
/// Without this, silently dropping a kind from the converter would leave
/// the fixture comparison passing against a regenerated — and now
/// impoverished — expectation.
#[test]
fn the_fixture_exercises_the_structural_node_kinds_the_renderer_switches_on() {
    let ast = actual();

    for kind in [
        "document",
        "section",
        "headline",
        "property-drawer",
        "node-property",
        "drawer",
        "planning",
        "clock",
        "timestamp",
        "keyword",
        "paragraph",
        "plain-list",
        "list-item",
        "src-block",
        "link",
        "bold",
        "code",
        "text",
    ] {
        assert!(
            !nodes_of_type(&ast, kind).is_empty(),
            "fixture no longer exercises node kind {kind:?}"
        );
    }

    assert_eq!(ast["type"], "document");

    let headlines = nodes_of_type(&ast, "headline");
    assert_eq!(headlines.len(), 2);
    assert_eq!(headlines[0]["todo_keyword"], "TODO");
    assert_eq!(headlines[0]["todo_type"], "todo");
    assert_eq!(headlines[0]["priority"], "A");
    assert_eq!(headlines[0]["tags"], serde_json::json!(["work", "urgent"]));
    assert_eq!(headlines[1]["todo_type"], "done");
    assert_eq!(headlines[1]["archived"], true);

    let planning = nodes_of_type(&ast, "planning");
    assert_eq!(planning[0]["entries"][0]["kind"], "scheduled");
    assert_eq!(planning[0]["entries"][1]["kind"], "deadline");
}

/// Every `source` range is a valid slice of the original input.
///
/// The AST omits Org delimiters from the semantic payload and tells
/// consumers they remain recoverable from `content` via `source`. That
/// promise is only true if the offsets are real UTF-8 byte boundaries.
#[test]
fn every_source_range_is_a_valid_utf8_slice_of_the_input() {
    let input = std::fs::read_to_string(fixture_dir().join("ast-contract.org"))
        .expect("ast-contract.org fixture must exist");
    let ast = actual();

    fn check(value: &Value, input: &str) {
        match value {
            Value::Object(map) => {
                if let Some(source) = map.get("source") {
                    let start = source["start"].as_u64().expect("start must be a number") as usize;
                    let end = source["end"].as_u64().expect("end must be a number") as usize;
                    assert!(start <= end, "inverted range {start}..{end}");
                    assert!(end <= input.len(), "range {start}..{end} exceeds input");
                    assert!(
                        input.is_char_boundary(start) && input.is_char_boundary(end),
                        "range {start}..{end} is not on a UTF-8 boundary"
                    );
                }
                for child in map.values() {
                    check(child, input);
                }
            }
            Value::Array(values) => {
                for child in values {
                    check(child, input);
                }
            }
            _ => {}
        }
    }

    check(&ast, &input);
    assert_eq!(ast["source"]["start"], 0);
    assert_eq!(ast["source"]["end"], input.len());
}
